export function ContractHeader({
  asset,
  slug,
  showActions: _showActions = true
}: {
  asset: Asset;
  slug?: string;
  showActions?: boolean;
}) {
  const { t } = useT();
  const tags = asset.tags ?? [];

  const tagStyle = (tag: string): { bg: string; text: string; ring: string; icon: React.ReactNode } => {
    const t = tag.toLowerCase();
    if (t.includes("pii") || t.includes("sensitive"))
      return { bg: "bg-red-50", text: "text-red-700", ring: "ring-red-600/20", icon: <svg className="h-3 w-3" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}><path strokeLinecap="round" strokeLinejoin="round" d="M12 9v3.75m-9.303 3.376c-.866 1.5.217 3.374 1.948 3.374h14.71c1.73 0 2.813-1.874 1.948-3.374L13.949 3.378c-.866-1.5-3.032-1.5-3.898 0L2.697 16.126ZM12 15.75h.007v.008H12v-.008Z" /></svg> };
    if (t.includes("gold") || t.includes("premium"))
      return { bg: "bg-amber-50", text: "text-amber-700", ring: "ring-amber-600/20", icon: <svg className="h-3 w-3" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}><path strokeLinecap="round" strokeLinejoin="round" d="M16.5 18.75h-9m9 0a3 3 0 0 1 3 3h-15a3 3 0 0 1 3-3m9 0v-3.375c0-.621-.503-1.125-1.125-1.125h-.871M7.5 18.75v-3.375c0-.621.504-1.125 1.125-1.125h.872m5.007 0H9.497m5.007 0a7.454 7.454 0 0 1-.982-3.172M9.497 14.25a7.454 7.454 0 0 0 .981-3.172M5.25 4.236c-.982.143-1.954.317-2.916.52A6.003 6.003 0 0 0 7.73 9.728M5.25 4.236V4.5c0 2.108.966 3.99 2.48 5.228M5.25 4.236V2.721C7.456 2.41 9.71 2.25 12 2.25c2.291 0 4.545.16 6.75.47v1.516M18.75 4.236c.982.143 1.954.317 2.916.52A6.003 6.003 0 0 1 16.27 9.728M18.75 4.236V4.5c0 2.108-.966 3.99-2.48 5.228m0 0a6.023 6.023 0 0 1-2.77.665 6.023 6.023 0 0 1-2.77-.665" /></svg> };
    if (t.includes("data-product") || t.includes("dataset"))
      return { bg: "bg-emerald-50", text: "text-emerald-700", ring: "ring-emerald-600/20", icon: <svg className="h-3 w-3" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}><path strokeLinecap="round" strokeLinejoin="round" d="M20.25 6.375c0 2.278-3.694 4.125-8.25 4.125S3.75 8.653 3.75 6.375m16.5 0c0-2.278-3.694-4.125-8.25-4.125S3.75 4.097 3.75 6.375m16.5 0v11.25c0 2.278-3.694 4.125-8.25 4.125s-8.25-1.847-8.25-4.125V6.375m16.5 0v3.75m-16.5-3.75v3.75m16.5 0v3.75C20.25 16.153 16.556 18 12 18s-8.25-1.847-8.25-4.125v-3.75m16.5 0c0 2.278-3.694 4.125-8.25 4.125s-8.25-1.847-8.25-4.125" /></svg> };
    if (t.includes("customer") || t.includes("crm") || t.includes("360"))
      return { bg: "bg-indigo-50", text: "text-indigo-700", ring: "ring-indigo-600/20", icon: <svg className="h-3 w-3" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}><path strokeLinecap="round" strokeLinejoin="round" d="M15 19.128a9.38 9.38 0 0 0 2.625.372 9.337 9.337 0 0 0 4.121-.952 4.125 4.125 0 0 0-7.533-2.493M15 19.128v-.003c0-1.113-.285-2.16-.786-3.07M15 19.128v.106A12.318 12.318 0 0 1 8.624 21c-2.331 0-4.512-.645-6.374-1.766l-.001-.109a6.375 6.375 0 0 1 11.964-3.07M12 6.375a3.375 3.375 0 1 1-6.75 0 3.375 3.375 0 0 1 6.75 0Zm8.25 2.25a2.625 2.625 0 1 1-5.25 0 2.625 2.625 0 0 1 5.25 0Z" /></svg> };
    if (t.includes("aggregat") || t.includes("source"))
      return { bg: "bg-blue-50", text: "text-blue-700", ring: "ring-blue-600/20", icon: <svg className="h-3 w-3" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}><path strokeLinecap="round" strokeLinejoin="round" d="M13.19 8.688a4.5 4.5 0 0 1 1.242 7.244l-4.5 4.5a4.5 4.5 0 0 1-6.364-6.364l1.757-1.757m9.856-3.16a4.5 4.5 0 0 0-1.242-7.244l-4.5-4.5a4.5 4.5 0 0 0-6.364 6.364L4.34 8.374" /></svg> };
    if (t.includes("json") || t.includes("avro") || t.includes("parquet") || t.includes("csv"))
      return { bg: "bg-slate-50", text: "text-slate-700", ring: "ring-slate-600/20", icon: <svg className="h-3 w-3" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}><path strokeLinecap="round" strokeLinejoin="round" d="M17.25 6.75 22.5 12l-5.25 5.25m-10.5 0L1.5 12l5.25-5.25m7.5-3-4.5 16.5" /></svg> };
    return { bg: "bg-gray-50", text: "text-gray-700", ring: "ring-gray-500/10", icon: <svg className="h-3 w-3" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}><path strokeLinecap="round" strokeLinejoin="round" d="M9.568 3H5.25A2.25 2.25 0 0 0 3 5.25v4.318c0 .597.237 1.17.659 1.591l9.581 9.581c.699.699 1.78.872 2.607.33a18.095 18.095 0 0 0 5.223-5.223c.542-.827.369-1.908-.33-2.607L11.16 3.66A2.25 2.25 0 0 0 9.568 3Z" /><path strokeLinecap="round" strokeLinejoin="round" d="M6 6h.008v.008H6V6Z" /></svg> };
  };
  const owner =
    asset.owners?.business_owner?.name ??
    asset.owners?.technical_owner?.name ??
    asset.owners?.business_owner?.email ??
    asset.owners?.technical_owner?.email ??
    t("platformTeam");

  const facts: Array<{ icon: React.ReactNode; label: string; value: string }> = [
    { icon: <IdIcon />, label: "Id", value: slug ?? getReadableValue(asset.id) },
    { icon: <VersionIcon />, label: t("version"), value: getReadableValue(asset.version) },
    { icon: <DomainIcon />, label: "Domain", value: getReadableValue(asset.domain) },
    { icon: <ContextIcon />, label: "Contexte", value: getReadableValue(asset.context) },
    { icon: <MaturityIcon />, label: t("maturity"), value: getReadableValue(asset.maturity) },
    { icon: <OwnerIcon />, label: t("owner"), value: owner },
  ];

  return (
    <section className="contract-hero" style={{ paddingLeft: 0, paddingRight: 0 }}>
      <div className="w-full">
        <div className="px-4 sm:px-0">
          <div className="flex flex-wrap items-center gap-x-3 gap-y-1.5">
            <h1 className="text-base font-semibold leading-6 text-gray-900">{asset.name ?? "Unknown contract"}</h1>
            {facts.map((fact, i) => (
              <span
                key={i}
                className="inline-flex items-center gap-1 rounded-md bg-gray-50 px-2 py-0.5 text-xs font-medium text-gray-700 ring-1 ring-inset ring-gray-500/10"
              >
                {fact.icon}
                <span className="text-gray-500">{fact.label}:</span>
                <strong className="font-semibold">{fact.value}</strong>
              </span>
            ))}
          </div>

          {tags.length > 0 ? (
            <div className="mt-3 flex flex-wrap items-center gap-1.5">
              <span className="text-xs font-medium text-gray-500">Tags :</span>
              {tags.map((tag) => {
                const s = tagStyle(tag);
                return (
                  <span
                    key={tag}
                    className={`inline-flex items-center gap-1 rounded-full px-2 py-0.5 text-xs font-semibold ring-1 ring-inset ${s.bg} ${s.text} ${s.ring}`}
                  >
                    {s.icon}
                    {tag}
                  </span>
                );
              })}
            </div>
          ) : null}
        </div>
      </div>
    </section>
  );
}
